# 32. A square garden with a side length of 150 m has a square swimming pool in the very centre with a side length of 25 m . Calculate the area of the garden.

total_garden_side_length = 150
swimming_side_length = 25

remaining_garden_area = (4*total_garden_side_length)-(4*swimming_side_length)

print(f"Area of garden: {remaining_garden_area}")